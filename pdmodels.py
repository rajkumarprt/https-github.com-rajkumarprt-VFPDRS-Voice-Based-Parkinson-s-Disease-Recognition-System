def evaluate_model(name, model, X_train_data, y_train_data, X_test_data, y_test_data, param_grid=None, use_proba=True):
    print(f"\n--- Evaluating {name} ---")

    start_train_time = time.time()
    if param_grid:
        grid_search = GridSearchCV(model, param_grid, scoring='recall', cv=5, n_jobs=-1)
        grid_search.fit(X_train_data, y_train_data)
        best_model = grid_search.best_estimator_
        train_time = time.time() - start_train_time
        print(f"Best Parameters: {grid_search.best_params_}")
        print(f"Best CV Score (Recall): {grid_search.best_score_:.4f}")
    else:
        model.fit(X_train_data, y_train_data)
        best_model = model
        train_time = time.time() - start_train_time

    start_pred_time = time.time()
    y_pred = best_model.predict(X_test_data)
    pred_time = time.time() - start_pred_time

    accuracy = accuracy_score(y_test_data, y_pred)
    precision = precision_score(y_test_data, y_pred, average='weighted')
    recall = recall_score(y_test_data, y_pred, average='weighted')
    f1 = f1_score(y_test_data, y_pred, average='weighted')

    roc_auc = -1 # Default if proba not available
    if use_proba and hasattr(best_model, 'predict_proba'):
        y_pred_proba = best_model.predict_proba(X_test_data)[:, 1]
        roc_auc = roc_auc_score(y_test_data, y_pred_proba)
    elif use_proba and not hasattr(best_model, 'predict_proba'):
        print(f"Warning: {name} does not support predict_proba, AUROC will not be calculated.")

    print(f"Accuracy: {accuracy:.4f}")
    print(f"Precision: {precision:.4f}")
    print(f"Recall: {recall:.4f}")
    print(f"F1-Score: {f1:.4f}")
    if roc_auc != -1:
        print(f"AUROC: {roc_auc:.4f}")
    print(f"Training Time: {train_time:.4f} seconds")
    print(f"Prediction Time: {pred_time:.4f} seconds")
    print("Classification Report:\n", classification_report(y_test_data, y_pred))

    cm = confusion_matrix(y_test_data, y_pred)
    # Reuse the global plot_confusion_matrix function if it's defined.
    # Ensure it's passed with appropriate classes.
    try:
        plot_confusion_matrix(cm, classes=["Not Parkinson", "Parkinson"], title=f'Confusion Matrix for {name}')
    except NameError:
        print("plot_confusion_matrix function not found, skipping plot.")
        plt.figure(figsize=(5, 5))
        sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=["Not Parkinson", "Parkinson"], yticklabels=["Not Parkinson", "Parkinson"])
        plt.xlabel('Predicted')
        plt.ylabel('Actual')
        plt.title(f'Confusion Matrix for {name}')
        plt.show()

    results.append({
        'Model': name,
        'Accuracy': accuracy,
        'Precision': precision,
        'Recall': recall,
        'F1-Score': f1,
        'AUROC': roc_auc,
        'Training Time': train_time,
        'Prediction Time': pred_time
    })

